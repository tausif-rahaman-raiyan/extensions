/**
 * Hourly rotating quote generator
 * Changes strictly every 1 hour based on date & current hour
 */
export function getHourlyQuote(now: Date = new Date()): IslamicQuote {
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
  const currentHour = now.getHours();

  // Unique index per hour of the year
  const hourlyIndex = Math.abs(dayOfYear * 24 + currentHour) % ISLAMIC_QUOTES.length;
  return ISLAMIC_QUOTES[hourlyIndex];
}
