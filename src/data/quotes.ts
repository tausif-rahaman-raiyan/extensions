/**
 * Returns an hourly rotating quote strictly in Bengali based on current time.
 */
export function getHourlyQuote(date: Date = new Date()): IslamicQuote {
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
  const currentHour = date.getHours();

  // Consistent mathematical hash by day + hour across the 65+ quotes
  const quoteIndex = Math.abs(dayOfYear * 24 + currentHour) % ISLAMIC_QUOTES.length;
  return ISLAMIC_QUOTES[quoteIndex];
}
